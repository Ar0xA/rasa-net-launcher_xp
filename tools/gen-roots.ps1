# Turns a PEM bundle (curl's cacert.pem, from Mozilla) into src/roots.inc: the root
# certificates BearSSL validates HTTPS servers against. XP's own root store is too old.
#
#   .\tools\gen-roots.ps1                       # third_party\cacert.pem -> src\roots.inc
#   .\tools\gen-roots.ps1 -Pem path\to\cacert.pem
param(
    [string]$Pem = "$PSScriptRoot\..\third_party\cacert.pem",
    [string]$Out = "$PSScriptRoot\..\src\roots.inc"
)
$ErrorActionPreference = 'Stop'

$text = Get-Content -Raw $Pem
$blocks = [regex]::Matches($text, '-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----', 'Singleline')
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("// Generated by tools/gen-roots.ps1 from $(Split-Path -Leaf $Pem). Do not edit.")
$n = 0
foreach ($m in $blocks) {
    $der = [Convert]::FromBase64String(($m.Groups[1].Value -replace '\s', ''))
    [void]$sb.Append("static const unsigned char root_$n[] = {")
    for ($i = 0; $i -lt $der.Length; $i++) {
        if ($i % 24 -eq 0) { [void]$sb.Append("`n ") }
        [void]$sb.Append("0x{0:x2}," -f $der[$i])
    }
    [void]$sb.AppendLine("`n};")
    $n++
}
[void]$sb.AppendLine("static const struct { const unsigned char *der; size_t len; } kRoots[] = {")
for ($i = 0; $i -lt $n; $i++) { [void]$sb.AppendLine("  { root_$i, sizeof root_$i },") }
[void]$sb.AppendLine("};")
[IO.File]::WriteAllText((Resolve-Path -LiteralPath (Split-Path $Out)).Path + '\' + (Split-Path -Leaf $Out), $sb.ToString())
Write-Host "$n root certificates written to $Out"
